#!/usr/bin/env python3
"""Render verified lesson JSON into the repository's static study-page shell."""
import argparse
import html
import json
import re
from html.parser import HTMLParser
from pathlib import Path
from string import Template
from urllib.parse import unquote, urlsplit

MARKER = '<!-- Generated by nce1-lesson-html.'
SECTION_NAMES = [('lesson', 'READ & UNDERSTAND', 'Lesson', '课文'),
                 ('practice', 'MAKE IT YOUR OWN', 'Practice', '练习'),
                 ('grammar', 'BUILD YOUR FOUNDATION', 'Grammar', '语法练习')]

def esc(value):
    return html.escape(str(value), quote=True)

def prose(value):
    return esc(value).replace('\n', '<br />\n')

def local_path(root, href):
    url = urlsplit(href)
    if url.scheme or url.netloc:
        raise ValueError(f'Expected local source/asset: {href}')
    path = (root / 'html' / unquote(url.path)).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError(f'Path escapes repository: {href}')
    return path

def step(root, number, direction, available):
    n = number + (-1 if direction == 'previous' else 1)
    label = '← <span>Previous</span>' if direction == 'previous' else '<span>Next</span> →'
    if n in available:
        control = f'<a href="lesson-{n:03}.html" aria-label="{direction.title()} lesson — Lesson {n}">{label}</a>'
        detail = f'Lesson {n}'
    else:
        detail = f'Lesson {n} · coming next' if 1 <= n <= 144 else 'End of book'
        control = f'<button type="button" disabled aria-label="{esc(detail)}">{label}</button>'
    return f'<div class="page-step {direction}">{control}<small>{detail}</small></div>'

class PageAudit(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids, self.refs, self.labels, self.answers = [], [], [], []
    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if 'id' in a: self.ids.append(a['id'])
        if 'for' in a: self.labels.append(a['for'])
        for key in ['href', 'src']:
            if key in a: self.refs.append(a[key])
        if 'data-answer' in a: self.answers.append(a)

def audit(root, rendered, available):
    page = PageAudit(); page.feed(rendered)
    if len(page.ids) != len(set(page.ids)): raise ValueError('Duplicate HTML IDs')
    required = {'lesson-form','lesson','practice','grammar','submit-answers','copy-dialog',
                'copy-report','select-report','close-dialog','copy-status','section-menu',
                'answered-count','question-count','answer-progress'}
    if not required <= set(page.ids): raise ValueError('Missing shared-JS hooks')
    if not set(page.labels) <= set(page.ids): raise ValueError('Broken label target')
    for ref in page.refs:
        if ref.startswith('#'):
            if ref[1:] not in page.ids: raise ValueError(f'Broken anchor: {ref}')
        else:
            path = local_path(root, ref)
            if path.name in {f'lesson-{n:03}.html' for n in available}: continue
            if not path.is_file(): raise ValueError(f'Missing source/asset: {ref}')
    for a in page.answers:
        for key in ['data-group','data-number','data-prompt','data-key']:
            if not a.get(key): raise ValueError(f'Missing {key}: {a}')
    return len([a for a in page.answers if 'data-example' not in a])

def render(root, d, available):
    n = d['number']
    if type(n) is not int or not 45 <= n <= 144: raise ValueError('Expected lesson 45–144')
    if d['status'] != 'verified': raise ValueError('Finish source verification before rendering')
    images = d.get('images', {})
    used_images, count = set(), 0
    for key, im in images.items():
        if im['kind'] not in ['scene','item','action']: raise ValueError(f'Invalid image kind: {key}')
        if not im.get('description') or not im.get('source'): raise ValueError(f'Missing image cue: {key}')
        if im['status'] not in ['pending','ready']: raise ValueError(f'Invalid image status: {key}')
        if im['status'] == 'ready':
            if not local_path(root, im['src']).is_file(): raise ValueError(f'Missing image: {key}')
            if not im.get('width') or not im.get('height'): raise ValueError(f'Missing dimensions: {key}')
        elif im.get('src'): raise ValueError(f'Pending image must not have src: {key}')
        if not set(im.get('characters', [])) <= set(d.get('characters', {})):
            raise ValueError(f'Unknown recurring character: {key}')

    def block(b, section):
        nonlocal count
        kind = b['type']
        if kind == 'text':
            content = f'<div class="reading-prompt"><p>{prose(b["text"])}</p>'
            if b.get('translation'): content += f'<p lang="zh-CN">{prose(b["translation"])}</p>'
            content += '</div>'
        elif kind == 'dialogue':
            content = '<ol class="dialogue">'
            for line in b['lines']:
                content += f'<li><span class="line-number">{esc(line["number"])}</span><div><p class="small-label">{esc(line["speaker"])}</p><p class="spoken">{prose(line["text"])}</p><p class="translation" lang="zh-CN">{prose(line["translation"])}</p></div></li>'
            content += '</ol>'
        elif kind == 'vocabulary':
            content = '<article class="vocabulary-block"><h3>New words &amp; expressions <span lang="zh-CN">生词和短语</span></h3><dl class="vocabulary">'
            for word in b['items']:
                content += f'<div><dt>{esc(word["word"])} <span class="phonetic">{esc(word["ipa"])}</span></dt><dd><span class="word-type">{esc(word["pos"])}</span> <span lang="zh-CN">{esc(word["meaning"])}</span></dd></div>'
            content += '</dl></article>'
        elif kind == 'notes':
            content = '<article class="lesson-notes"><h3>Notes on the text <span lang="zh-CN">课文注释</span></h3><div class="note-grid">'
            for note in b['items']:
                content += f'<div><span class="small-label">{esc(note["title"])}</span><p lang="zh-CN">{prose(note["text"])}</p></div>'
            content += '</div></article>'
        elif kind == 'exercise':
            if len(b['questions']) != b['expected_items']:
                raise ValueError(f'Coverage mismatch: {b["id"]}')
            content = f'<article class="exercise"><header class="exercise-heading"><h3>{esc(b["title"])}</h3><p class="instruction">{prose(b["instruction"])}</p><p lang="zh-CN">{prose(b["translation"])}</p></header>'
            if b.get('word_bank'):
                content += '<div class="word-bank">' + ''.join(f'<span>{esc(w)}</span>' for w in b['word_bank']) + '</div>'
            if b.get('context'): content += f'<p>{prose(b["context"])}</p>'
            for q in b['questions']:
                example = q.get('example', False)
                key = q['answer']
                provenance = q.get('answer_kind', b.get('answer_kind'))
                if provenance not in ['source-key','suggested','source-example']: raise ValueError(f'Unknown answer provenance: {q["id"]}')
                if provenance == 'source-key' and not b.get('key_source'): raise ValueError('Missing key source')
                if provenance == 'suggested': key += ' (Suggested answer / 参考答案)'
                opts = ' readonly data-example' if example else ''
                group = f'{section.title()} · {b["title"]}'
                content += f'<div class="question{" example" if example else ""}"><label for="{esc(q["id"])}"><span class="question-number">{esc(q["number"])}</span><span>{prose(q["prompt"])}</span></label><textarea id="{esc(q["id"])}" name="{esc(q["id"])}" data-answer data-group="{esc(group)}" data-number="{esc(q["number"])}" data-prompt="{esc(q["prompt"])}" data-key="{esc(key)}" rows="{int(q.get("rows", 3))}" spellcheck="false" placeholder="Write your answer…"{opts}>{esc(q["answer"]) if example else ""}</textarea></div>'
                if not example: count += 1
            content += '</article>'
        else:
            raise ValueError(f'Unsupported block type: {kind}')
        slot = b.get('image')
        if slot:
            if slot in used_images: raise ValueError(f'Duplicate slot: {slot}')
            used_images.add(slot)
            im = images[slot]
            if im['status'] == 'ready':
                figure = f'<figure class="question-illustration"><img src="{esc(im["src"])}" alt="{esc(im["description"])}" width="{im["width"]}" height="{im["height"]}" loading="lazy" /><figcaption>{esc(im.get("caption", slot))}</figcaption></figure>'
                content = f'<div class="illustrated-question{" dialogue-scene" if kind == "dialogue" else ""}" data-image-slot="{esc(slot)}">{figure}{content}</div>'
            else:
                content = f'<div data-image-slot="{esc(slot)}">{content}</div>'
        return f'<div id="{esc(b["id"])}">{content}</div>'

    sections = []
    if set(d['sections']) != {'lesson','practice','grammar'}: raise ValueError('Expected all three sections')
    for i, (section, eyebrow, title, zh) in enumerate(SECTION_NAMES, 1):
        content = '\n'.join(block(b, section) for b in d['sections'][section])
        sections.append(f'<section id="{section}" class="lesson-section" aria-labelledby="{section}-title"><header class="section-heading"><span class="section-number">{i:02}</span><div><p class="eyebrow">{eyebrow}</p><h2 id="{section}-title">{title} <span lang="zh-CN">{zh}</span></h2></div></header>\n{content}\n</section>')
    if used_images != set(images): raise ValueError('Unused image slots')
    if count != d['expected_answers']: raise ValueError(f'Expected {d["expected_answers"]} answers, found {count}')
    sources = ''.join(f'<li><a href="{esc(s["href"])}" target="_blank" rel="noopener">{esc(s["label"])} <span>↗</span></a></li>' for s in d['sources'])
    template = Template((Path(__file__).resolve().parent.parent / 'assets/lesson.html').read_text())
    result = template.substitute(number=f'{n:03}', ordinal=n, title=esc(d['title']), translation=esc(d['translation']), description=prose(d['description']), answer_note=esc(d['answer_note']), meta_description=esc(f'New Concept English Book 1, Lesson {n}: {d["title"]}. Read the lesson and complete the workbook and grammar exercises.'), count=count, sections='\n'.join(sections), sources=sources, previous=step(root,n,'previous',available), next=step(root,n,'next',available))
    audit(root, result, available)
    return result, count

def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--repo', type=Path, default=Path.cwd())
    p.add_argument('--from', dest='first', type=int, required=True)
    p.add_argument('--to', dest='last', type=int, required=True)
    p.add_argument('--check', action='store_true', help='Validate and require byte-for-byte matching HTML; no writes')
    args = p.parse_args()
    if not 45 <= args.first <= args.last <= 144: p.error('Range must be within 45–144')
    root = args.repo.resolve()
    requested = set(range(args.first, args.last + 1))
    available = {int(path.stem.split('-')[1]) for path in (root/'html').glob('lesson-[0-9][0-9][0-9].html')} | requested
    outputs = []
    for n in sorted(requested):
        data = json.loads((root / f'lessons/lesson-{n:03}.json').read_text())
        if data['number'] != n: raise ValueError('Filename/lesson mismatch')
        result, count = render(root, data, available)
        path = root / f'html/lesson-{n:03}.html'
        if path.exists() and MARKER not in path.read_text(): raise ValueError(f'Refusing to replace an unmanaged page: {path}')
        if args.check and (not path.exists() or path.read_text() != result): raise ValueError(f'Out-of-date output: {path}')
        outputs.append((path, result, count))
    # Validate the full requested batch before writing any page.
    for path, result, count in outputs:
        if not args.check: path.write_text(result)
        print(f'{"Checked" if args.check else "Rendered"} {path.name}: {count} editable answers')

if __name__ == '__main__':
    main()
